# Regenerates the Solace API client from the frozen contract.
#
# Pin discipline:
#   - generator wrapper: @openapitools/openapi-generator-cli 2.13.0 (npm)
#   - generator:         7.12.0 (set both here and in openapitools.json the first run creates)
#   - contract:          services/api/openapi.yaml — its SHA-256 is written to CONTRACT.lock
#
# Output: packages/api-client (standalone dart-dio package) — committed, never hand-edited.
# apps/mobile depends on it via `Solace_api: { path: ../api-client }`.
# CI (Phase 13) re-runs this script and fails on any diff.
param(
    [string]$RepoRoot = (Join-Path $PSScriptRoot '..\..')
)

$FlutterRoot = $null
$candidates = @(
    $env:FLUTTER_ROOT,
    "C:\src\flutter",
    "D:\src\flutter",
    "E:\src\flutter",
    "C:\flutter",
    "D:\flutter"
) | Where-Object { $_ }
foreach ($c in $candidates) {
    $dartBat = Join-Path $c "bin\dart.bat"
    $dartExe = Join-Path $c "bin\dart.exe"
    if (Test-Path $dartBat) { $FlutterRoot = $c; break }
    if (Test-Path $dartExe) { $FlutterRoot = $c; break }
}
if (-not $FlutterRoot) {
    $onPath = Get-Command dart -ErrorAction SilentlyContinue
    if ($onPath) { $Dart = $onPath.Source }
    else {
        throw "Could not locate the Dart SDK. Set FLUTTER_ROOT to your Flutter installation (e.g. C:\src\flutter)."
    }
} else {
    $dartBat = Join-Path $FlutterRoot "bin\dart.bat"
    $dartExe = Join-Path $FlutterRoot "bin\dart.exe"
    if (Test-Path $dartBat) { $Dart = $dartBat }
    elseif (Test-Path $dartExe) { $Dart = $dartExe }
    else { throw "Dart binary not found under $FlutterRoot\bin" }
}
$Contract = (Resolve-Path (Join-Path $RepoRoot 'services\api\openapi.yaml')).Path -replace '\\','/'
# dart-dio output is a standalone package (imports package:Solace_api/...),
# so it lives outside the app and is referenced as a path dependency.
$OutDir = Join-Path $RepoRoot 'packages\api-client'
$LockFile = Join-Path $OutDir 'CONTRACT.lock'
$GeneratorVersion = '7.12.0'
$JarUrl = "https://repo1.maven.org/maven2/org/openapitools/openapi-generator-cli/$GeneratorVersion/openapi-generator-cli-$GeneratorVersion.jar"
$JarDir = Join-Path $PSScriptRoot '.cache'
$JarPath = Join-Path $JarDir "openapi-generator-cli-$GeneratorVersion.jar"

# Fetch the pinned generator jar once (checksum recorded; retried on flaky links).
New-Item -ItemType Directory -Force -Path $JarDir | Out-Null
if (-not (Test-Path $JarPath)) {
    $tmp = "$JarPath.download"
    for ($attempt = 1; $attempt -le 3; $attempt++) {
        try {
            Invoke-WebRequest -Uri $JarUrl -OutFile $tmp -UseBasicParsing -TimeoutSec 300
            Move-Item $tmp $JarPath -Force
            break
        } catch {
            Write-Output "jar download attempt $attempt failed: $($_.Exception.Message)"
            Start-Sleep -Seconds 3
        }
    }
    if (-not (Test-Path $JarPath)) {
        throw "Could not download generator jar from $JarUrl"
    }
    Write-Output "Downloaded $JarPath"
}
& java -jar $JarPath version

if (-not (Test-Path $Contract)) {
    throw "Contract not found: $Contract"
}

# Freeze marker: hash of exactly the contract the output was generated from.
$shader = Get-FileHash $Contract -Algorithm SHA256
$sourceRevision = git -C $RepoRoot rev-parse HEAD:services/api/openapi.yaml
$lock = @"
# GENERATED by tools/openapi/generate-client.ps1 — do not edit.
contract: services/api/openapi.yaml
contract_sha256: $($shader.Hash.ToLower())
contract_gitrev: $sourceRevision
generator: openapi-generator $GeneratorVersion (dart-dio)
wrapper: openapi-generator-cli $WrapperVersion
generated_at: $((Get-Date).ToUniversalTime().ToString('o'))
"@

& java -jar $JarPath generate `
    --input-spec $Contract `
    --generator-name dart-dio `
    --output $OutDir `
    --additional-properties=pubName=Solace_api,pubVersion=0.1.0,pubLibrary=Solace_api,dateLibrary=core,legacyDiscriminatorBehavior=false,useEnumsForNumericMapKeys=false,separatorLegacyBehavior=false

if ($LASTEXITCODE -ne 0) {
    throw "openapi-generator failed with exit code $LASTEXITCODE"
}

# Built-value serializers are generated by build_runner so the package is
# self-contained for consumers (no build_runner step at app build time).
Push-Location $OutDir
try {
    & $Dart pub get
    if ($LASTEXITCODE -ne 0) { throw "dart pub get failed in $OutDir" }
    & $Dart run build_runner build --delete-conflicting-outputs
    if ($LASTEXITCODE -ne 0) { throw "build_runner failed in $OutDir" }
} finally {
    Pop-Location
}

$lock = @"
# GENERATED by tools/openapi/generate-client.ps1 — do not edit.
contract: services/api/openapi.yaml
contract_sha256: $($shader.Hash.ToLower())
contract_gitrev: $sourceRevision
generator: openapi-generator $GeneratorVersion (dart-dio)
output: $OutDir
generated_at: $((Get-Date).ToUniversalTime().ToString('o'))
"@
Set-Content -Path $LockFile -Value $lock -Encoding UTF8
Write-Output "Generated client in $OutDir"
Write-Output "Contract hash written to $LockFile"
